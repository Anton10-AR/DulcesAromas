-- Módulo Seguridad: cuentas, roles fijos con permisos editables, sesiones y auditoría.

create table rol (
	codigo varchar(20) primary key
);

create table rol_permiso (
	rol     varchar(20) not null references rol (codigo),
	permiso varchar(40) not null,
	primary key (rol, permiso)
);

create table usuario (
	id                 bigint generated by default as identity primary key,
	tipo               varchar(10)  not null,
	nombre             varchar(100) not null,
	correo             varchar(254) not null,
	telefono           varchar(20),
	contrasena_hash    varchar(100) not null,
	activo             boolean      not null,
	intentos_fallidos  integer      not null,
	bloqueado_hasta    timestamp with time zone,
	creado             timestamp with time zone not null,
	direccion_habitual varchar(255),
	rol                varchar(20) references rol (codigo),
	constraint usuario_correo_unico unique (correo),
	constraint usuario_tipo check (tipo in ('CLIENTE', 'PERSONAL')),
	-- RN16: un cliente nunca tiene rol de personal; el personal siempre tiene uno.
	constraint usuario_rol_segun_tipo check (
		(tipo = 'CLIENTE' and rol is null) or (tipo = 'PERSONAL' and rol is not null))
);

create table sesion (
	id         bigint generated by default as identity primary key,
	token_hash varchar(64) not null,
	usuario_id bigint      not null references usuario (id),
	creada     timestamp with time zone not null,
	ultimo_uso timestamp with time zone not null,
	constraint sesion_token_unico unique (token_hash)
);

create index sesion_usuario on sesion (usuario_id);

create table auditoria (
	id         bigint generated by default as identity primary key,
	usuario_id bigint references usuario (id),
	accion     varchar(40)   not null,
	detalle    varchar(1000) not null,
	fecha      timestamp with time zone not null
);

create index auditoria_fecha on auditoria (fecha);

