-- Máximo de unidades por pedido (RN18, RF44) y recetas aproximadas para estimar insumos y tiempo (RF45, RF46, D12).
-- Las recetas solo estiman: no descuentan stock ni cambian la disponibilidad, que sigue siendo manual (D2).

alter table producto add column maximo_por_pedido integer;
alter table producto add column minutos_por_unidad integer;
alter table producto add constraint producto_maximo_positivo check (maximo_por_pedido is null or maximo_por_pedido between 1 and 99);
alter table producto add constraint producto_minutos_positivos check (minutos_por_unidad is null or minutos_por_unidad between 1 and 1440);

-- Cuánto multiplica una opción la receta y el tiempo: una torta Grande lleva más que una Mediana.
alter table opcion_personalizacion add column factor numeric(4, 2) not null default 1;
alter table opcion_personalizacion add constraint opcion_factor_positivo check (factor > 0);

-- Copia del factor al pedir, como el nombre y el recargo, para que un cambio en el producto no altere el pedido.
alter table opcion_elegida add column factor numeric(4, 2) not null default 1;

create table ingrediente_receta (
	id          bigint generated by default as identity primary key,
	producto_id bigint         not null references producto (id),
	orden       integer        not null,
	insumo_id   bigint         not null references item_inventario (id),
	-- En la unidad del insumo, por cada unidad del producto.
	cantidad    numeric(12, 3) not null,
	constraint ingrediente_cantidad_positiva check (cantidad > 0),
	constraint ingrediente_insumo_unico unique (producto_id, insumo_id)
);

create index ingrediente_producto on ingrediente_receta (producto_id);
