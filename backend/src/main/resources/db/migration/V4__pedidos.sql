-- Módulo E-commerce, pedidos: configuración, pedidos con sus líneas y opciones elegidas, e historial de estados.

-- Una sola fila (id = 1). La tarifa inicial sale de la landing («desde Bs 10»); el administrador la cambia.
create table configuracion (
	id           smallint       primary key,
	tarifa_envio numeric(10, 2) not null,
	constraint configuracion_una_fila check (id = 1),
	constraint configuracion_tarifa_no_negativa check (tarifa_envio >= 0)
);

insert into configuracion (id, tarifa_envio) values (1, 10.00);

create table pedido (
	id                 bigint generated by default as identity primary key,
	cliente_id         bigint         not null references usuario (id),
	-- Quien registró un pedido asistido (CU17); nulo si lo hizo el propio cliente.
	registrado_por     bigint         references usuario (id),
	estado             varchar(20)    not null,
	tipo_entrega       varchar(10)    not null,
	direccion          varchar(255),
	telefono           varchar(20)    not null,
	horario_entrega    timestamp with time zone not null,
	costo_envio        numeric(10, 2) not null,
	total              numeric(10, 2) not null,
	fecha_creacion     timestamp with time zone not null,
	motivo_cancelacion varchar(255),
	constraint pedido_tipo_entrega check (tipo_entrega in ('RECOJO', 'DELIVERY')),
	-- RN12: el delivery exige dirección.
	constraint pedido_delivery_con_direccion check (tipo_entrega = 'RECOJO' or direccion is not null)
);

create index pedido_cliente on pedido (cliente_id);
create index pedido_estado on pedido (estado);

create table linea_pedido (
	id              bigint generated by default as identity primary key,
	pedido_id       bigint         not null references pedido (id),
	orden           integer        not null,
	producto_id     bigint         not null references producto (id),
	-- Copias del momento del pedido, para que un cambio en el producto no altere pedidos anteriores.
	nombre_producto varchar(100)   not null,
	precio_unitario numeric(10, 2) not null,
	cantidad        integer        not null,
	mensaje         varchar(24),
	subtotal        numeric(10, 2) not null,
	constraint linea_cantidad_positiva check (cantidad > 0)
);

create index linea_pedido_pedido on linea_pedido (pedido_id);

create table opcion_elegida (
	id       bigint generated by default as identity primary key,
	linea_id bigint         not null references linea_pedido (id),
	orden    integer        not null,
	tipo     varchar(40)    not null,
	nombre   varchar(60)    not null,
	recargo  numeric(10, 2) not null
);

create index opcion_elegida_linea on opcion_elegida (linea_id);

create table historial_estado (
	id              bigint generated by default as identity primary key,
	pedido_id       bigint       not null references pedido (id),
	estado_anterior varchar(20),
	estado_nuevo    varchar(20)  not null,
	fecha           timestamp with time zone not null,
	usuario_id      bigint       references usuario (id),
	observacion     varchar(500)
);

create index historial_estado_pedido on historial_estado (pedido_id);
