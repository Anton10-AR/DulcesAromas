-- Módulo E-commerce, inventario de insumos (CU03). No se relaciona con la disponibilidad de los productos (D2).

create table item_inventario (
	id           bigint generated by default as identity primary key,
	nombre       varchar(60)    not null,
	nombre_clave varchar(60)    not null,
	unidad       varchar(20)    not null,
	stock        numeric(12, 3) not null,
	minimo       numeric(12, 3) not null,
	constraint item_inventario_nombre_unico unique (nombre_clave),
	-- RN09 y RNF14: el stock nunca queda negativo.
	constraint item_inventario_stock_no_negativo check (stock >= 0),
	constraint item_inventario_minimo_no_negativo check (minimo >= 0)
);

create table movimiento_inventario (
	id               bigint generated by default as identity primary key,
	item_id          bigint         not null references item_inventario (id),
	tipo             varchar(10)    not null,
	cantidad         numeric(12, 3) not null,
	stock_resultante numeric(12, 3) not null,
	motivo           varchar(255)   not null,
	usuario_id       bigint         not null references usuario (id),
	fecha            timestamp with time zone not null,
	constraint movimiento_tipo check (tipo in ('ENTRADA', 'SALIDA', 'AJUSTE'))
);

create index movimiento_inventario_item on movimiento_inventario (item_id);
