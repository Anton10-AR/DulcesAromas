-- Módulo Cobros: métodos de pago editables (RNF18), pagos con comprobante y verificaciones.

create table metodo_pago (
	id             bigint generated by default as identity primary key,
	nombre         varchar(40)   not null,
	nombre_clave   varchar(40)   not null,
	-- Datos para pagar que ve el cliente: número de cuenta, titular, banco.
	instrucciones  varchar(1000) not null,
	activo         boolean       not null,
	qr_actualizado timestamp with time zone,
	constraint metodo_pago_nombre_unico unique (nombre_clave)
);

-- Empiezan desactivados: el administrador completa los datos para pagar y los activa,
-- para que ningún cliente vea datos de cuenta de ejemplo.
insert into metodo_pago (nombre, nombre_clave, instrucciones, activo) values
	('QR', 'qr', '', false),
	('Transferencia', 'transferencia', '', false),
	('Depósito', 'deposito', '', false);

create table qr_metodo_pago (
	metodo_pago_id bigint      primary key references metodo_pago (id),
	tipo_contenido varchar(20) not null,
	datos          bytea       not null
);

-- Un pedido tiene varios pagos: cada comprobante rechazado deja su pago y se abre otro (RN07).
create table pago (
	id             bigint generated by default as identity primary key,
	pedido_id      bigint         not null references pedido (id),
	monto          numeric(10, 2) not null,
	estado         varchar(20)    not null,
	metodo_pago_id bigint         references metodo_pago (id),
	-- Copia del nombre del método, por si luego se renombra.
	metodo_nombre  varchar(40),
	referencia     varchar(60),
	creado         timestamp with time zone not null,
	registrado     timestamp with time zone
);

create index pago_pedido on pago (pedido_id);
create index pago_estado on pago (estado);

create table comprobante (
	pago_id        bigint      primary key references pago (id),
	tipo_contenido varchar(20) not null,
	datos          bytea       not null
);

-- Quién aprobó o rechazó cada pago y cuándo (RF39, RNF08).
create table verificacion (
	id             bigint generated by default as identity primary key,
	pago_id        bigint       not null references pago (id),
	decision       varchar(10)  not null,
	observacion    varchar(500),
	verificador_id bigint       not null references usuario (id),
	fecha          timestamp with time zone not null,
	constraint verificacion_decision check (decision in ('APROBADO', 'RECHAZADO')),
	-- RN07: rechazar exige observación.
	constraint verificacion_rechazo_con_observacion check (decision = 'APROBADO' or observacion is not null)
);

create index verificacion_pago on verificacion (pago_id);
