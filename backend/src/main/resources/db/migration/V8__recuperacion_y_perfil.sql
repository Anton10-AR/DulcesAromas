-- Recuperar contraseña (CU12) y cambio obligatorio tras un restablecimiento del administrador.

alter table usuario add column debe_cambiar_contrasena boolean default false not null;

-- Enlace de un solo uso para que el cliente defina una contraseña nueva. Solo se guarda el hash del token.
create table recuperacion_contrasena (
	id         bigint generated by default as identity primary key,
	usuario_id bigint      not null references usuario (id),
	token_hash varchar(64) not null,
	expira     timestamp with time zone not null,
	usada      boolean     not null,
	constraint recuperacion_token_unico unique (token_hash)
);

create index recuperacion_usuario on recuperacion_contrasena (usuario_id);
