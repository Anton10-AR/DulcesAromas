-- Módulo Distribución: una entrega por pedido con delivery, con su repartidor y sus asignaciones.

create table entrega (
	id                bigint generated by default as identity primary key,
	pedido_id         bigint       not null references pedido (id),
	repartidor_id     bigint       not null references usuario (id),
	fecha_asignacion  timestamp with time zone not null,
	fecha_entrega     timestamp with time zone,
	-- Observación de la última entrega fallida (RN13).
	observacion_fallo varchar(500),
	constraint entrega_un_pedido unique (pedido_id)
);

create index entrega_repartidor on entrega (repartidor_id);

-- Cada asignación o cambio de repartidor, con quién lo hizo y cuándo (CU08, alt. 4).
create table asignacion_entrega (
	id            bigint generated by default as identity primary key,
	entrega_id    bigint not null references entrega (id),
	repartidor_id bigint not null references usuario (id),
	asignado_por  bigint not null references usuario (id),
	fecha         timestamp with time zone not null
);

create index asignacion_entrega_entrega on asignacion_entrega (entrega_id);
