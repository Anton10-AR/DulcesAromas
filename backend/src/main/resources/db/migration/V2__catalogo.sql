-- Módulo E-commerce, catálogo: categorías, productos, opciones de personalización e imágenes.

create table categoria (
	id            bigint generated by default as identity primary key,
	nombre        varchar(60) not null,
	-- Nombre sin mayúsculas, tildes ni espacios repetidos, para que «Tortas» y «tortas» no convivan.
	nombre_clave  varchar(60) not null,
	activa        boolean     not null,
	constraint categoria_nombre_unico unique (nombre_clave)
);

create table producto (
	id                 bigint generated by default as identity primary key,
	categoria_id       bigint        not null references categoria (id),
	nombre             varchar(100)  not null,
	-- Nombre sin mayúsculas ni tildes, para buscar «torta» y encontrar «Tórta».
	nombre_busqueda    varchar(100)  not null,
	descripcion        varchar(1000) not null,
	precio             numeric(10, 2) not null,
	activo             boolean       not null,
	disponible         boolean       not null,
	personalizable     boolean       not null,
	imagen_actualizada timestamp with time zone,
	constraint producto_precio_positivo check (precio > 0)
);

create index producto_categoria on producto (categoria_id);

create table opcion_personalizacion (
	id          bigint generated by default as identity primary key,
	producto_id bigint         not null references producto (id),
	orden       integer        not null,
	tipo        varchar(40)    not null,
	nombre      varchar(60)    not null,
	recargo     numeric(10, 2) not null,
	constraint opcion_recargo_no_negativo check (recargo >= 0)
);

create index opcion_producto on opcion_personalizacion (producto_id);

-- La imagen va aparte para no cargar sus bytes cada vez que se lee un producto.
create table imagen_producto (
	producto_id    bigint      primary key references producto (id),
	tipo_contenido varchar(20) not null,
	datos          bytea       not null
);
